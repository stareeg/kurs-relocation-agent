-- 0156_agent_run_usage — токены и цена запуска агента (E-9).
--
-- agent_runs.usage — расход запуска на момент последней записи статуса (пауза, итог,
-- остановка): вызовы модели, токены вход/выход, цена, из неё условная цена моделей
-- своей ВМ, разбивка по группам (агент, субагенты, судья, LLM внутри инструментов) и
-- пределы запуска. Пустой объект — запуск до E-9 или ещё не дошёл до первой записи.
--
-- llm_usage.agent_run_id — к какому запуску агента относится вызов модели. Колонку
-- заполняет синк из контекста задачи запуска; по ней сумма токенов запуска сверяется с
-- независимым журналом вызовов (клиент модели пишет его из сырого usage HTTP-ответа).
-- Без внешнего ключа: журнал вызовов не должен зависеть от судьбы строки запуска.

alter table agent_runs add column usage jsonb not null default '{}'::jsonb;

alter table llm_usage add column agent_run_id bigint;

create index llm_usage_agent_run_idx on llm_usage (agent_run_id) where agent_run_id is not null;
