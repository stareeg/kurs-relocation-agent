/**
 * Данные под «Шанс офферов»: вклады факторов — гистограмма по категориям (`CategoryBars`)
 * вместо одной полосы сегментами base=100. Каждый фактор — отдельный столбец.
 *
 * Правка (план `offer_chance_rework_2026_08_11`, Шаг 8): высота столбца — сырой суб-балл
 * фактора (`score * 100`, 0..100), не `contribution` (`weight * score * 100`). До этой правки
 * фактор с весом 5% физически не мог подняться выше 5 на общей шкале `0..100`, даже если
 * кандидат по нему на максимуме — ось путала «вес фактора» с «качеством кандидата по фактору».
 * Теперь `yMax: 100` честный: любой столбец может физически достичь верха. Сам вес виден
 * отдельно — числом внутри самого столбца (`CategoryBar.inBarLabel`), не в подписи под ним.
 *
 * Линейный график истории шанса во времени убран из этого блока (правка 2026-08-11, жалоба
 * «выглядит кривовато») — карточка теперь только сводка + вклады факторов. История шанса
 * (`useMarketChanceHistory`) остаётся в коде — её ещё использует фон шкалы периода
 * (`PeriodRangeSlider.tsx`), просто не рисуется здесь.
 *
 * Чистая подготовка — без БД и без React, тестируется отдельно от `MarketPage.tsx`.
 */
import type { OfferChanceComponent } from "@/api/market"
import type { CategoryBar } from "./charts/category-bars-geometry"

/** Короткие подписи столбцов для тесной колонки (план 2026-08-11 п.3) — бэк отдаёт полные
 * термины («Качество резюме», «Рынок под вас», «Активность»), тут — их сжатая форма.
 * Факторы не в этой карте (Воронка/Скиллы/Отклики/Этапы) остаются как есть. */
const SHORT_FACTOR_LABELS: Readonly<Record<string, string>> = {
  resume_quality: "Резюме",
  market: "Рынок",
  activity: "Общение",
}

/** Форма единственного/множественного числа для «N балл/балла/баллов» — подпись вклада
 * фактора в итоговый скор (правка 2026-08-14: теперь в верхе столбца, не вес). */
function pointsLabel(value: number): string {
  const n = Math.round(value)
  const lastTwo = n % 100
  if (lastTwo >= 11 && lastTwo <= 14) return `${n} баллов`
  const last = n % 10
  if (last === 1) return `${n} балл`
  if (last >= 2 && last <= 4) return `${n} балла`
  return `${n} баллов`
}

/** «62/100 · вес 25% · вклад 16 в итог» — тройная подпись тултипа: суб-балл фактора, его текущий
 * вес и итоговый вклад в композит. Заменяет старую двойную «вклад/потолок» — потолок фактора
 * (`weight × 100`) был путающей величиной, суб-балл фактора честнее отвечает на «как я тут
 * выступаю», а вклад — на «сколько это дало итогу». */
export function offerChanceFactorTooltipValue(component: OfferChanceComponent): string {
  const sub = Math.round(component.score * 100)
  const weightPct = Math.round(component.weight * 100)
  const contribution = Math.round(component.contribution)
  return `${sub}/100 · вес ${weightPct}% · вклад ${contribution} в итог`
}

/**
 * Вклады факторов для `CategoryBars`: каждый фактор — отдельный столбец, высота = суб-балл
 * фактора (0..100), общая шкала Y = 0..100. Порядок — как пришёл с бэка (`_WEIGHTS` в
 * `pulse.py`, семантический, не по весу: воронка → техготовность → качество резюме → рынок →
 * отклики → активность → глубина воронки) — сохраняется как есть, столбцы не переставляются,
 * иначе они «прыгали» бы местами при динамическом сдвиге весов (§1.3 плана).
 *
 * Правка 2026-08-14: подписи внутри столбца перераспределены. Раньше `inBarLabel` (верх
 * столбца) нёс вес фактора («25%»). Теперь:
 *  * верх столбца (`inBarLabel`) — вклад фактора в итоговый балл шанса оффера («21 балл»),
 *    отвечает на «сколько это дало итогу»;
 *  * низ столбца (`bottomInBarLabel`) — вес фактора («25%»), отвечает на «какой это фактор по
 *    значимости». Так читается сверху вниз: «21 балл / 25%» — понятно, что фактор весом 25%
 *    дал 21 балл из своих возможных 25.
 */
export function offerChanceFactorBars(components: readonly OfferChanceComponent[]): CategoryBar[] {
  return components.map((c) => ({
    key: c.key,
    label: SHORT_FACTOR_LABELS[c.key] ?? c.label,
    value: Math.max(0, c.score * 100),
    inBarLabel: pointsLabel(c.contribution),
    bottomInBarLabel: `${Math.round(c.weight * 100)}%`,
  }))
}
