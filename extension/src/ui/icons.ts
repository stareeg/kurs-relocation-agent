export interface IconOptions {
  /** Пиксельный размер (16 = w-4, 20 = w-5). По умолчанию 16. */
  size?: number
  strokeWidth?: number
  /** Доп. CSS-класс (например, для анимации вращения loader). */
  className?: string
}

/** Возвращает SVGElement готовой к вставке lucide-иконки. */
export function icon(name: IconName, opts: IconOptions = {}): SVGSVGElement {
  const size = opts.size ?? 16
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg')
  svg.setAttribute('xmlns', 'http://www.w3.org/2000/svg')
  svg.setAttribute('viewBox', '0 0 24 24')
  svg.setAttribute('width', String(size))
  svg.setAttribute('height', String(size))
  svg.setAttribute('fill', 'none')
  svg.setAttribute('stroke', 'currentColor')
  svg.setAttribute('stroke-width', String(opts.strokeWidth ?? 1.75))
  svg.setAttribute('stroke-linecap', 'round')
  svg.setAttribute('stroke-linejoin', 'round')
  svg.setAttribute('aria-hidden', 'true')
  if (opts.className) svg.setAttribute('class', opts.className)
  svg.innerHTML = ICON_BODIES[name]
  return svg
}

/** То же, но строкой (когда нужно вставить в innerHTML-шаблон). */
export function iconMarkup(name: IconName, opts: IconOptions = {}): string {
  const size = opts.size ?? 16
  const cls = opts.className ? ` class="${opts.className}"` : ''
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="${size}" height="${size}"` +
    ` fill="none" stroke="currentColor" stroke-width="${opts.strokeWidth ?? 1.75}"` +
    ` stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"${cls}>` +
    `${ICON_BODIES[name]}</svg>`
  )
}
